"""Correlation identifiers for runs.

Unlike ``domain.ids`` (business entities: tickets, employees), these ids describe *runs*
of the harness. They are generated by the server, never taken from user input:

* ``RequestId``: one user turn. Every event, trace, audit record and cost-ledger row
  produced while handling that turn carries it, so they can be joined later.
* ``ThreadId``: one conversation (a LangGraph thread). Spans many requests.
* ``EventId``: one event (M02 ``Event``), unique across all runs.

Same ``NewType`` trick as ``domain.ids``: plain ``str`` at runtime, distinct for pyright.
The prefix makes ids readable in logs and JSONL files (``req_…`` vs ``thr_…``).
"""

import uuid
from typing import NewType

RequestId = NewType("RequestId", str)
ThreadId = NewType("ThreadId", str)
EventId = NewType("EventId", str)


def _new(prefix: str) -> str:
    # uuid4: random, no clock or host information leaks into the id.
    return f"{prefix}_{uuid.uuid4().hex}"


def new_request_id() -> RequestId:
    return RequestId(_new("req"))


def new_thread_id() -> ThreadId:
    return ThreadId(_new("thr"))


def new_event_id() -> EventId:
    return EventId(_new("evt"))
